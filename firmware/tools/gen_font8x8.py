FIRST, LAST = 0x20, 0x7E


def rows_for(ch):
    art = GLYPHS.get(ch)
    if art is None:                     # 未定義は塗りつぶしの箱で目立たせる
        art = ("#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####")
    out = []
    for line in art:
        bits = 0
        for x, cell in enumerate(line):
            if cell != ' ':
                bits |= 1 << x          # bit0 = 左端
        out.append(bits)
    out.append(0)                       # 8 行目は行間
    return out


def render(ch):
    print("--- %r (0x%02X)" % (ch, ord(ch)))
    for byte in rows_for(ch):
        print(''.join('#' if byte & (1 << x) else '.' for x in range(8)))


def emit():
    lines = [
        "// 生成物。手で直さず tools/gen_font8x8.py を直して作り直すこと。",
        "// 5x7 の自作ドット絵を 8x8 の枠に入れたもの。段階 0 の起動画面と",
        "// 診断表示だけに使う (ステータスバーの本番フォントは素材側の efont h24)。",
        "// bit0 が左端の画素。1 バイトが 1 行。",
        "#include \"stackee_font8x8.h\"",
        "",
        "const uint8_t stackee_font8x8[STACKEE_FONT_COUNT][8] = {",
    ]
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        body = ', '.join('0x%02X' % b for b in rows_for(ch))
        shown = ch if ch not in ('\\',) else '\\\\'
        lines.append("    {%s},  // 0x%02X '%s'" % (body, code, shown))
    lines.append("};")
    lines.append("")
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--show', metavar='TEXT', nargs='?', const=None,
                    default=False, help='生成せずに絵を表示する')
    args = ap.parse_args()
    if args.show is not False:
        text = args.show or ''.join(chr(c) for c in range(FIRST, LAST + 1))
        for ch in text:
            render(ch)
        return 0
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'main', 'stackee_font8x8.c')
    with open(out, 'w') as f:
        f.write(emit())
    print('書いた: %s (%d 文字)' % (os.path.normpath(out), LAST - FIRST + 1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
